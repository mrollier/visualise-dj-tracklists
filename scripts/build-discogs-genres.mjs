// Builds src/data/discogs-genres.json: the Discogs400 style taxonomy the
// v39 analysed-genre layer needs, as `style → parent labels` in the shape
// src/data/genre-tree.json uses.
//
//   node scripts/build-discogs-genres.mjs        (after scripts/fetch-models.sh)
//
// The model's own labels are `Parent---Style` over 15 Discogs top-level
// genres, so the taxonomy is two free levels — no hand-mapping of 400 styles.
// Only the 15 parents are a judgement call, and they are the table below.
// Sixteen styles live under two parents ("Disco" is both Electronic and
// Funk / Soul); the curated tree is a DAG too, so they keep both.
import { readFileSync, writeFileSync } from 'node:fs'

const MODEL = 'scripts/models/genre_discogs400-discogs-effnet-1.json'
const OUT = 'src/data/discogs-genres.json'

/** Discogs' 15 top-level genres → the curated tree's own nodes. Anything
 * with no home in a club library's taxonomy attaches to the root, where its
 * information content is low and it can never drive a strong match. */
const PARENT = {
  Electronic: 'electronic',
  Rock: 'rock',
  Pop: 'pop',
  Jazz: 'jazz',
  Latin: 'latin',
  Reggae: 'reggae',
  'Hip Hop': 'hip hop',
  // Discogs' Funk / Soul spans both; 'soul' is the broader of the two here.
  'Funk / Soul': 'soul',
  'Folk, World, & Country': 'folk',
  // The tree has no blues node and r&b is where its lineage lands.
  Blues: 'r&b',
  Classical: 'music',
  'Stage & Screen': 'music',
  'Non-Music': 'music',
  'Brass & Military': 'music',
  "Children's": 'music',
}

const classes = JSON.parse(readFileSync(MODEL, 'utf8')).classes
const parents = {}
for (const label of classes) {
  const [parent, style] = label.split('---')
  const mapped = PARENT[parent]
  if (mapped === undefined) throw new Error(`no tree parent mapped for "${parent}"`)
  // A style that IS its own parent would make a cycle out of a lineage.
  if (style.toLowerCase() === mapped) continue
  parents[style] = [...new Set([...(parents[style] ?? []), mapped])]
}

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      _readme: [
        'GENERATED by scripts/build-discogs-genres.mjs — do not hand-edit.',
        'The 400 Discogs styles the genre_discogs400 head predicts, as',
        'style → parent labels of the curated genre-tree.json. Keys are the',
        "model's own spelling; the app normalizes them (normalizeGenre) on",
        'load, and the curated tree always wins a collision.',
      ],
      parents,
    },
    null,
    1,
  )}\n`,
)
console.log(`${OUT}: ${Object.keys(parents).length} styles from ${classes.length} labels`)
